"""HEOSAT sub-web: Apereo's Higher Education Open Source Assessment Toolkit as an evidence-backed self-assessment.

Generated from ecosystem/heosat-evidence-map.json: the hub, one tile per rubric section and one per question, each
question tied to the ecosystem web nodes that answer it. A gap question has nothing to tie to and renders as a gap
(ghosted, dashed); a partial one says what is missing. Details in hax-heosat.json."""
import json, re
MAP = "prawrepo/ecosystem/heosat-evidence-map.json"
PRAW = "https://github.com/haxtheweb/praw/blob/main/"
def S(c, *i): return {"caption": c, "nodes": list(i)}
D = json.load(open(MAP))
SECS, QS = D["sections"], {q["id"]: q for q in D["questions"]}
MAIN = set(re.findall(r"^\s+(\w+)[\[\(\{>]", open("hax-ecosystem.mmd").read(), re.M))
evidence_nodes = sorted({n for q in QS.values() for n in q["nodes"]} | {p for s in SECS for p in s["pillars"]})
missing = [n for n in evidence_nodes if n not in MAIN]
assert not missing, f"map names nodes the main web doesn't draw: {missing}"
CONTEXT = ["apereo", "praw", "traveler", "wins", "booklooky"]
count = {k: sum(1 for q in QS.values() if q["status"] == k) for k in ("evidenced", "partial", "gap")}
def qid(i): return "hq_" + i.lower()
def sid(i): return "hs_" + i.lower()
lines = ["%% HEOSAT sub-web: Apereo's Higher Education Open Source Assessment Toolkit, generated by build_heosat.py from ecosystem/heosat-evidence-map.json.",
         "%% Each question links to the ecosystem web nodes that answer it; gaps link to nothing. Portals: ids from hax-ecosystem.mmd and hax-skills.mmd. Details in hax-heosat.json.",
         "flowchart TB", "  %%@ layout rings=0,250,500,800 sizes=92,64,40,50",
         '  subgraph hub ["HEOSAT"]', '    heosat["heosat"]', "  end", '  subgraph who ["Who runs it"]']
for c in CONTEXT: lines.append(f'    {c}["{c}"]')
lines += ['    s_heosat["s_heosat"]', "  end", '  subgraph secs ["Sections"]']
for s in SECS: lines.append(f'    {sid(s["id"])}["{s["title"]}"]')
lines += ["  end", '  subgraph qsg ["Questions"]']
for q in QS.values(): lines.append(f'    {qid(q["id"])}["{q["id"]}"]')
lines += ["  end", '  subgraph ev ["Answered by"]']
for n in evidence_nodes:
    if n not in CONTEXT: lines.append(f'    {n}["{n}"]')
lines += ["  end", "",
          "  heosat --o|is published by| apereo", "  heosat -->|is run through| s_heosat", "  s_heosat --o|lives in| praw", "  traveler -->|runs the assessment with AI through| s_heosat",
          "  wins -->|records| booklooky", "  heosat -->|helped| booklooky", "  booklooky --o|went through incubation at| apereo"]
for s in SECS:
    lines.append(f"  heosat -->|scores| {sid(s['id'])}")
    for p in s["pillars"]: lines.append(f"  {sid(s['id'])} ==>|serves| {p}")
    for i in s["questions"]: lines.append(f"  {sid(s['id'])} -->|asks| {qid(i)}")
for q in QS.values():
    for n in q["nodes"]: lines.append(f"  {qid(q['id'])} -.->|{'answered by' if q['status'] == 'evidenced' else 'partly answered by'}| {n}")
lines += ["", "  %%@ group hub tier=0", "  %%@ group who tier=3", "  %%@ group secs tier=1", "  %%@ group qsg tier=2", "  %%@ group ev tier=3",
          "  %%@ node heosat portal", "  %%@ node s_heosat portal=skills"]
for c in CONTEXT: lines.append(f"  %%@ node {c} portal")
for s in SECS: lines.append(f"  %%@ node {sid(s['id'])} mono={s['id']} color=beaverBlue motion=pop")
COL = {"evidenced": "forestGreen", "partial": "roarGolden", "gap": "limestoneGray"}
for q in QS.values(): lines.append(f"  %%@ node {qid(q['id'])} mono={q['id']} color={COL[q['status']]} motion=nudge")
for n in evidence_nodes:
    if n not in CONTEXT: lines.append(f"  %%@ node {n} portal")
open("hax-heosat.mmd", "w").write("\n".join(lines) + "\n")

STATUS = {"evidenced": "deployed", "partial": "in-progress", "gap": "gap"}
WORD = {"evidenced": "Evidenced", "partial": "Partly evidenced", "gap": "Gap: no evidence yet"}
nodes = {"heosat": {"always": True}, "s_heosat": {}}
for s in SECS:
    qs = [QS[i] for i in s["questions"]]
    c = {k: sum(1 for q in qs if q["status"] == k) for k in ("evidenced", "partial", "gap")}
    nodes[sid(s["id"])] = {"desc": f"{s['title']}: {len(qs)} questions. {c['evidenced']} evidenced, {c['partial']} partial, {c['gap']} gap{'s' if c['gap'] != 1 else ''}.", "kind": "section",
                           "source": {"label": "heosat-evidence-map.json", "url": PRAW + "ecosystem/heosat-evidence-map.json"}}
for q in QS.values():
    links = {}
    for e in q.get("evidence", [])[:8]: links[e["label"]] = e["url"]
    nodes[qid(q["id"])] = {"desc": q["text"] + (f" {q['note']}" if q.get("note") else ""), "status": STATUS[q["status"]], "kind": q["status"],
                           "note": f"{WORD[q['status']]}. Section: {next(s['title'] for s in SECS if s['id'] == q['section'])}.", "links": links}
gaps = [q for q in QS.values() if q["status"] == "gap"]; partial = [q for q in QS.values() if q["status"] == "partial"]
tours = [{"id": "heosat", "label": "HEOSAT, question by question", "kind": "story",
          "message": f"{len(QS)} questions in {len(SECS)} sections: {count['evidenced']} evidenced, {count['partial']} partial, {count['gap']} gaps.",
          "scenes": [S("Apereo publishes HEOSAT. HAX runs it with AI through the heosat skill in PRAW, a process worked out with Apereo.", "heosat", "apereo", "s_heosat", "praw", "traveler")] +
                    [S(f"{s['title']}.", sid(s["id"]), *[qid(i) for i in s["questions"]], *sorted({n for i in s["questions"] for n in QS[i]["nodes"]})) for s in SECS] +
                    [S("Partly evidenced: mostly docs mid-rebuild, procurement answers, and reviews documented but not yet held.", *[qid(q["id"]) for q in partial]),
                     S("The gaps: " + "; ".join(f"{q['id']}, {q['text'].rstrip('.')}" for q in gaps) + ".", *[qid(q["id"]) for q in gaps]),
                     S("A win: HAX's HEOSAT work helped fellow project BookLooky go through Apereo incubation more accurately.", "booklooky", "heosat", "apereo", "wins"),
                     S("The whole assessment.")]}]
meta = {"name": "HEOSAT", "parent": "main", "noTimeline": True,
        "sectionLabels": {"section": "sections", "evidenced": "evidenced", "partial": "partly evidenced", "gap": "gaps"},
        "about": f"Apereo's Higher Education Open Source Assessment Toolkit as a standing self-assessment, generated from heosat-evidence-map.json. The tool's rubric ({D['rubric']['version']}) scores {len(QS)} questions in {len(SECS)} sections; each question links to the parts of HAX that answer it. {count['evidenced']} evidenced (green), {count['partial']} partial (amber, in progress) and {count['gap']} gaps (ghosted, dashed). A self-assessment for maintainer review, not a HEOSAT score.",
        "kindLabels": {"rel": "sections and questions", "schema": "answered by", "pillar": "pillars a section serves", "org": "Apereo and PRAW"},
        "links": {"map": PRAW + "ecosystem/heosat-evidence-map.json", "heosat": "https://github.com/apereo/heosat", "issue": "https://github.com/haxtheweb/issues/issues/3256"}}
json.dump({"meta": meta, "nodes": nodes, "evidence": {}, "tours": tours}, open("hax-heosat.json", "w"), indent=1, ensure_ascii=False)
print(len(SECS), "sections;", len(QS), "questions;", count, ";", len(evidence_nodes), "nodes answer them")
