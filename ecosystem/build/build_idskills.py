"""Instructional design skills sub-web: PRAW's instructional design skills, the HAX elements each recommends or checks,
and the pillars each upholds. Generated from ecosystem/id-skills-map.json. Elements no skill covers, and skills with no
element to act on, show as gaps (https://github.com/haxtheweb/issues/issues/3257). Opens from the Instructional design
tile in the skills web. Details in hax-idskills.json."""
import json, re
MAP = "prawrepo/ecosystem/id-skills-map.json"
WC = "https://github.com/haxtheweb/webcomponents/tree/master/elements/"
PRAW = "https://github.com/haxtheweb/praw/blob/main/"
def S(c, *i): return {"caption": c, "nodes": list(i)}
def slug(s): return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")
D = json.load(open(MAP)); SK = D["skills"]; COV = D["coverage"]
SKILL_IDS = set(re.findall(r"^\s+(s_\w+)\[", open("hax-skills.mmd").read(), re.M))
EL_IDS = set(re.findall(r"^\s+(b_\w+)\[", open("hax-elements.mmd").read(), re.M))
MAIN = set(re.findall(r"^\s+(\w+)[\[\(\{>]", open("hax-ecosystem.mmd").read(), re.M))
def sk(s): return "s_" + s.replace("-", "_")
def el(e): return "b_" + e.replace("-", "_")
missing = [s["skill"] for s in SK if sk(s["skill"]) not in SKILL_IDS] + [n for s in SK for n in s["nodes"] + s["pillars"] if n not in MAIN]
assert not missing, f"map names tiles the webs don't draw: {missing}"
FAM = list(dict.fromkeys(s["family"] for s in SK))
elements = sorted({e for s in SK for e in s["elements"]})
uncovered = [x["element"] for x in COV["elementsNoSkillCovers"]]
no_el = COV["skillsWithNoElement"]
pillars = sorted({p for s in SK for p in s["pillars"]})
others = sorted({n for s in SK for n in s["nodes"]} - set(pillars))
lines = ["%% Instructional design skills sub-web, generated by build_idskills.py from ecosystem/id-skills-map.json.",
         "%% Skills are portals to hax-skills.mmd; elements in the HAX app store are portals to hax-elements.mmd; pillars and parts to hax-ecosystem.mmd.",
         "flowchart TB", "  %%@ layout rings=0,190,430,720,960 sizes=92,60,46,40,50",
         '  subgraph hub ["Instructional design"]', '    g_id["g_id"]', "  end", '  subgraph fams ["Families"]']
for f in FAM: lines.append(f'    if_{slug(f)}["{f}"]')
lines += ["  end", '  subgraph skg ["Skills"]']
for s in SK: lines.append(f'    {sk(s["skill"])}["{s["skill"]}"]')
lines += ["  end", '  subgraph elg ["Elements they recommend or check"]']
for e in elements + uncovered: lines.append(f'    {el(e)}["{e}"]')
lines += ["  end", '  subgraph pg ["Pillars and parts"]']
for n in pillars + others: lines.append(f'    {n}["{n}"]')
lines += ["  end", ""]
for f in FAM: lines.append(f"  g_id -->|includes| if_{slug(f)}")
for s in SK:
    lines.append(f"  if_{slug(s['family'])} -->|includes| {sk(s['skill'])}")
    for e in s["elements"]: lines.append(f"  {sk(s['skill'])} -->|recommends or checks| {el(e)}")
    for p in s["pillars"]: lines.append(f"  {sk(s['skill'])} ==>|upholds| {p}")
    for n in s["nodes"]: lines.append(f"  {sk(s['skill'])} -.->|works with| {n}")
lines += ["", "  %%@ group hub tier=0", "  %%@ group fams tier=1", "  %%@ group skg tier=2", "  %%@ group elg tier=3", "  %%@ group pg tier=4", "  %%@ node g_id portal=skills"]
for f in FAM: lines.append(f"  %%@ node if_{slug(f)} icon=hax:lesson color=forestGreen motion=pop")
for s in SK: lines.append(f"  %%@ node {sk(s['skill'])} portal=skills")
for e in elements + uncovered:
    lines.append(f"  %%@ node {el(e)} portal=elements" if el(e) in EL_IDS and e not in uncovered else f"  %%@ node {el(e)} icon=hax:bricks color={'limestoneGray' if e in uncovered else 'creekTeal'} motion=nudge")
for n in pillars + others: lines.append(f"  %%@ node {n} portal")
open("hax-idskills.mmd", "w").write("\n".join(lines) + "\n")
by_el = {e: [s["skill"] for s in SK if e in s["elements"]] for e in elements}
nodes = {"g_id": {}}
for f in FAM:
    fs = [s for s in SK if s["family"] == f]
    nodes[f"if_{slug(f)}"] = {"desc": f"{f}: {len(fs)} skill{'s' if len(fs) != 1 else ''}, recommending or checking {len({e for s in fs for e in s['elements']})} elements.", "kind": "family"}
for s in SK:
    if s["skill"] in no_el: nodes[sk(s["skill"])] = {"status": "gap", "note": "Gap: no HAX element for this skill to act on yet."}
for e in elements:
    if el(e) not in EL_IDS:
        nodes[el(e)] = {"desc": f"@haxtheweb/{e}. Recommended or checked by {len(by_el[e])} skill{'s' if len(by_el[e]) != 1 else ''}: {', '.join(by_el[e])}.", "links": {"repo": WC + e}, "kind": "element"}
for x in COV["elementsNoSkillCovers"]:
    nodes[el(x["element"])] = {"desc": f"@haxtheweb/{x['element']}. {x['note']}", "status": "gap", "note": "Gap: no instructional design skill covers this element yet.", "links": {"repo": WC + x["element"], "issue": "https://github.com/haxtheweb/issues/issues/3257"}, "kind": "gap"}
top = sorted(elements, key=lambda e: -len(by_el[e]))[:8]
tours = [{"id": "idskills", "label": "Skills, elements and pillars", "kind": "story", "message": f"{len(SK)} instructional design skills, the {len(elements)} elements they recommend or check, and the pillars they uphold.", "scenes": [
    S(f"{len(FAM)} families of instructional design skills in PRAW.", *[f"if_{slug(f)}" for f in FAM]),
    *[S(f"{f}.", f"if_{slug(f)}", *[sk(s["skill"]) for s in SK if s["family"] == f], *sorted({el(e) for s in SK if s["family"] == f for e in s["elements"]})) for f in FAM],
    S("The elements skills reach for most: " + ", ".join(top) + ".", *[el(e) for e in top]),
    S("Each skill upholds pillars (proposed for review in haxtheweb/issues#3257).", *pillars, *[sk(s["skill"]) for s in SK]),
    S("Gaps: elements no skill covers yet, and a skill with no element to act on.", *[el(e) for e in uncovered], *[sk(s) for s in no_el]),
    S("All of it.")]}]
meta = {"name": "Instructional design skills", "parent": "skills", "noTimeline": True, "sectionLabels": {"family": "families", "element": "elements", "gap": "gaps"},
        "about": f"PRAW's {len(SK)} instructional design skills, the {len(elements)} HAX elements their own files recommend or check, and the pillars they uphold, generated from id-skills-map.json. Pillar links are proposed for review. Ghosted tiles are gaps: {len(uncovered)} elements no skill covers and {len(no_el)} skill with no element to act on.",
        "kindLabels": {"rel": "families, skills and the elements they act on", "pillar": "pillars a skill upholds", "schema": "parts a skill works with"},
        "links": {"map": PRAW + "ecosystem/id-skills-map.json", "issue": "https://github.com/haxtheweb/issues/issues/3257"}}
json.dump({"meta": meta, "nodes": nodes, "evidence": {}, "tours": tours}, open("hax-idskills.json", "w"), indent=1, ensure_ascii=False)
print(len(SK), "skills;", len(elements), "elements;", len(uncovered), "uncovered;", len(no_el), "skills with no element")
