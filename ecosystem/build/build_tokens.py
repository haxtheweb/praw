"""DDD token export sub-web: the design system as W3C Design Tokens Community Group (DTCG) JSON.

Generated from the webcomponents source (the sparse clone in sources.sh): the token files in elements/d-d-d/tokens
(token groups, types, aliases and dark-mode overrides counted from the JSON, with group types inherited the DTCG way),
the source files build-tokens.js reads (found in design-system/lib/source.js), the CI steps in ddd-token-lint.yml, and
the tools the tokens README names. It also runs `build-tokens.js --check`: when the committed files are out of date
with the element source, the token files are marked stale and drift.py reports them. Details in hax-tokens.json."""
import json, re, os, glob, collections, subprocess
GH = "https://github.com/haxtheweb"
WCB = GH + "/webcomponents/blob/master/"
W = "wcrepo"
DDD = "elements/d-d-d"
TOK = f"{DDD}/tokens"
def S(c, *i): return {"caption": c, "nodes": list(i)}
def slug(s): return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")
MAIN = set(re.findall(r"^\s+(\w+)[\[\(\{>]", open("hax-ecosystem.mmd").read(), re.M))
QUALITY = set(re.findall(r"^\s+(\w+)[\[\(\{>]", open("hax-quality.mmd").read(), re.M))
def J(p): return json.load(open(os.path.join(W, p)))

# ---------- the token files ----------
files = sorted(os.path.basename(f) for f in glob.glob(f"{W}/{TOK}/*.json"))
def walk(o, path=(), typ=None):
    """yield (path, token, type) for every token; a group's $type applies to the tokens under it"""
    if not isinstance(o, dict): return
    typ = o.get("$type", typ)
    if "$value" in o: yield path, o, typ; return
    for k, v in o.items():
        if not k.startswith("$"): yield from walk(v, path + (k,), typ)
sets = {f: list(walk(J(f"{TOK}/{f}"))) for f in files if f.endswith(".tokens.json")}
light = next((f for f in sets if ".dark." not in f), None)
dark = next((f for f in sets if ".dark." in f), None)
themes = J(f"{TOK}/$themes.json") if "$themes.json" in files else []
metadata = J(f"{TOK}/$metadata.json") if "$metadata.json" in files else {}
def gkey(p): return ".".join(p[:2])
groups = collections.OrderedDict()
for p, t, typ in sets.get(light, []):
    g = groups.setdefault(gkey(p), {"n": 0, "alias": 0, "types": collections.Counter(), "dark": 0, "ex": "{0}".format(t.get("$extensions", {}).get("org.haxtheweb.ddd", {}).get("cssVar", ""))})
    g["n"] += 1; g["types"][typ or "untyped"] += 1
    if isinstance(t["$value"], str) and t["$value"].startswith("{"): g["alias"] += 1
for p, t, typ in sets.get(dark, []):
    if gkey(p) in groups: groups[gkey(p)]["dark"] += 1
types = collections.Counter(typ or "untyped" for p, t, typ in sets.get(light, []))
def gid(k): return "g_" + slug(k)
def tid(k): return "ty_" + slug(k)

# ---------- what writes them: the export script and the source it reads ----------
build = f"{DDD}/design-system/build-tokens.js"
src_js = open(os.path.join(W, DDD, "design-system/lib/source.js")).read() if os.path.exists(os.path.join(W, DDD, "design-system/lib/source.js")) else ""
sources = []
for args in re.findall(r"read\(\s*((?:\"[^\"]+\"\s*,?\s*)+)\)", src_js): sources.append("/".join(re.findall(r'"([^"]+)"', args)))
for f in re.findall(r'path\.join\(DDD_DIR,\s*"lib",\s*"([^"]+)"\)', src_js): sources.append(f"{DDD}/lib/{f}")
sources = [s for s in dict.fromkeys(sources) if s.endswith(".js")]
check = {"ok": None, "out": ""}
if os.path.exists(os.path.join(W, build)):
    try:
        r = subprocess.run(["node", build, "--check"], cwd=W, capture_output=True, text=True, timeout=120)
        check = {"ok": r.returncode == 0, "out": (r.stdout + r.stderr).strip().splitlines()[-1:] or [""]}
        check["out"] = check["out"][0][:300]
    except (OSError, subprocess.TimeoutExpired) as e: check = {"ok": None, "out": str(e)[:200]}

# ---------- what checks them: the CI steps ----------
wf = os.path.join(W, ".github/workflows/ddd-token-lint.yml")
ci = re.findall(r"-\s*name:\s*(.+)\n\s+run:\s*(.+)", open(wf).read()) if os.path.exists(wf) else []
QCHECK = "q_ddd_token_lint" if "q_ddd_token_lint" in QUALITY else None
# ---------- what reads them: the tools the README names ----------
readme = open(os.path.join(W, TOK, "README.md")).read() if os.path.exists(os.path.join(W, TOK, "README.md")) else ""
m = re.search(r"for use in (.+?) and other tools", readme)
tools = [re.sub(r"\s*\(via ([^)]+)\)", r" via \1", t).strip() for t in re.split(r",\s*", m.group(1))] if m else []
PORTALS = [p for p in ["ddd", "components"] if p in MAIN]

lines = ["%% DDD token export sub-web, generated by build_tokens.py from elements/d-d-d/tokens and the export script in webcomponents.",
         "%% Portals: ids from hax-ecosystem.mmd and hax-quality.mmd. Details in hax-tokens.json.",
         "flowchart TB", "  %%@ layout rings=0,230,500,760,1000 sizes=92,58,44,46,46",
         '  subgraph hub ["DDD token export"]', '    dtcg[("dtcg")]', "  end", '  subgraph filesg ["Token files"]']
for f in files: lines.append(f'    f_{slug(f)}[("{f}")]')
lines += ["  end", '  subgraph groupsg ["Token groups"]']
for k, g in groups.items(): lines.append(f'    {gid(k)}["{k} ({g["n"]})"]')
lines += ["  end", '  subgraph typesg ["DTCG types"]']
for k in types: lines.append(f'    {tid(k)}["{k}"]')
lines += ["  end", '  subgraph toolsg ["Written from, checked by, read by"]', '    t_build["build-tokens.js"]']
for s in sources: lines.append(f'    s_{slug(os.path.basename(s))}["{os.path.basename(s)}"]')
for i, (name, run) in enumerate(ci): lines.append(f'    ci_{i}["{name.strip()}"]')
for t in tools: lines.append(f'    r_{slug(t)}["{t}"]')
if QCHECK: lines.append(f'    {QCHECK}["{QCHECK}"]')
for p in PORTALS: lines.append(f'    {p}["{p}"]')
lines += ["  end", ""]
for f in files: lines.append(f"  dtcg -->|is published as| f_{slug(f)}")
for k, g in groups.items():
    lines.append(f"  f_{slug(light)} -->|holds| {gid(k)}")
    if g["dark"] and dark: lines.append(f"  f_{slug(dark)} -.->|overrides in dark mode| {gid(k)}")
    lines.append(f"  {gid(k)} -.->|is typed| {tid(g['types'].most_common(1)[0][0])}")
for f in files: lines.append(f"  t_build -->|writes| f_{slug(f)}")
for s in sources: lines.append(f"  s_{slug(os.path.basename(s))} -->|feeds| t_build")
for i, (name, run) in enumerate(ci):
    lines.append(f"  ci_{i} -->|{'checks' if 'build-tokens' in run else 'lints against'}| {'t_build' if 'build-tokens' in run else 'dtcg'}")
    if QCHECK: lines.append(f"  {QCHECK} -->|runs| ci_{i}")
for t in tools:
    for f in files: lines.append(f"  f_{slug(f)} -.->|is read by| r_{slug(t)}") if f in (light, "$themes.json") else None
if "ddd" in PORTALS: lines.append("  ddd -->|is exported as| dtcg")
if "components" in PORTALS: lines.append("  components -->|use the tokens of| ddd" if "ddd" in PORTALS else "  components -->|use| dtcg")
lines += ["", "  %%@ group hub tier=0", "  %%@ group filesg tier=1", "  %%@ group groupsg tier=2", "  %%@ group typesg tier=3", "  %%@ group toolsg tier=4",
          "  %%@ node dtcg icon=lrn:palette color=creekTeal motion=pulse"]
stale = check["ok"] is False
for f in files: lines.append(f"  %%@ node f_{slug(f)} icon=hax:code-json color={'roarGolden' if stale else 'forestGreen'} motion=nudge")
for k in groups: lines.append(f"  %%@ node {gid(k)} icon=lrn:palette color={'athertonViolet' if k.startswith('simple-colors') else 'beaverBlue'} motion=pop")
for k in types: lines.append(f"  %%@ node {tid(k)} icon=hax:code-json color=slateGray motion=nudge")
lines.append("  %%@ node t_build icon=hax:code-json color=creekTeal motion=nudge")
for s in sources: lines.append(f"  %%@ node s_{slug(os.path.basename(s))} icon=hax:code-json color=slateGray motion=nudge")
for i, _ in enumerate(ci): lines.append(f"  %%@ node ci_{i} icon=icons:check-circle color=forestGreen motion=nudge")
for t in tools: lines.append(f"  %%@ node r_{slug(t)} icon=icons:extension color=limestoneGray motion=nudge")
if QCHECK: lines.append(f"  %%@ node {QCHECK} portal=quality")
for p in PORTALS: lines.append(f"  %%@ node {p} portal")
open("hax-tokens.mmd", "w").write("\n".join(lines) + "\n")

n_light = len(sets.get(light, [])); n_dark = len(sets.get(dark, [])); n_alias = sum(g["alias"] for g in groups.values())
state = {True: "In step with the element source: build-tokens.js --check passes.", False: "Out of date with the element source: build-tokens.js --check fails. Run yarn tokens:ddd.", None: "Not checked here (the export script could not run)."}[check["ok"]]
nodes = {"dtcg": {"always": True, "desc": f"DDD and SimpleColors as W3C DTCG design tokens, generated from the element source so design tools see exactly what the elements use: {n_light} tokens ({n_alias} of them aliases of another token), {n_dark} dark-mode overrides, {len(themes)} themes. {state}",
                  "links": {"tokens": GH + f"/webcomponents/tree/master/{TOK}", "DTCG": "https://www.designtokens.org/"}}}
ABOUT = {light: f"Every token with its light value: {n_light} in {len(groups)} groups. Each carries its CSS custom property in $extensions so tools can map back to var(--ddd-*).",
         dark: f"Only what changes in dark mode: {n_dark} overrides. Apply it on top of {light}.",
         "$themes.json": "The themes for Tokens Studio: " + ", ".join(f"{t.get('name')} ({', '.join(k for k, v in t.get('selectedTokenSets', {}).items() if v == 'enabled')})" for t in themes) + ".",
         "$metadata.json": "The set order for Tokens Studio's multi-file sync: " + ", ".join(metadata.get("tokenSetOrder", [])) + "."}
for f in files:
    d = {"desc": ABOUT.get(f, "A token file."), "kind": "file", "links": {"file": WCB + f"{TOK}/{f}"}}
    if stale: d.update(status="in-progress", note="Out of date with the element source.", stale=[check["out"] or "build-tokens.js --check fails"])
    nodes[f"f_{slug(f)}"] = d
for k, g in groups.items():
    nodes[gid(k)] = {"desc": f"{g['n']} tokens" + (f", {g['alias']} aliases" if g["alias"] else "") + (f", {g['dark']} change in dark mode" if g["dark"] else "") + ". Types: " + ", ".join(f"{t} {n}" for t, n in g["types"].most_common()) + "." + (f" For example {g['ex']}." if g["ex"] else ""), "kind": "group"}
for k, n in types.items():
    nodes[tid(k)] = {"desc": (f"{n} tokens are {k}." if k != "untyped" else f"{n} tokens carry no $type of their own or from their group."), "kind": "type"}
nodes["t_build"] = {"desc": f"Exports DDD and SimpleColors as DTCG from the element source; --check fails CI when the committed files are stale. Last check here: {check['out'] or 'not run'}.", "kind": "tool", "links": {"code": WCB + build}}
for s in sources: nodes[f"s_{slug(os.path.basename(s))}"] = {"desc": f"Element source the export reads: {s}.", "kind": "tool", "links": {"code": WCB + s}}
for i, (name, run) in enumerate(ci): nodes[f"ci_{i}"] = {"desc": f"A step of the ddd-token-lint workflow, which fails a webcomponents pull request: {run.strip()}", "kind": "tool", "links": {"workflow": WCB + ".github/workflows/ddd-token-lint.yml"}}
for t in tools: nodes[f"r_{slug(t)}"] = {"desc": f"Named in the tokens README as a tool that reads DTCG: {t}.", "kind": "reader", "links": {"README": WCB + f"{TOK}/README.md"}}
tours = [{"id": "tokens", "label": "DDD as design tokens", "kind": "story",
          "message": f"{n_light} tokens in {len(groups)} groups, {n_dark} dark-mode overrides, generated from the element source.",
          "scenes": [S("DDD lives in the elements' CSS. The export turns it into DTCG JSON that design tools read.", "dtcg", *[p for p in ["ddd"] if p in PORTALS], *[f"f_{slug(f)}" for f in files]),
                     S("The groups, named after the CSS custom properties.", *[gid(k) for k in groups if k.startswith("ddd")]),
                     S("SimpleColors comes along, fixed and default; the default palette flips in dark mode.", *[gid(k) for k in groups if k.startswith("simple-colors")], *([f"f_{slug(dark)}"] if dark else [])),
                     S("Every token has a DTCG type.", *[tid(k) for k in types]),
                     S("build-tokens.js reads the element source and writes the files; CI fails a pull request when they fall out of date.", "t_build", *[f"s_{slug(os.path.basename(s))}" for s in sources], *[f"ci_{i}" for i in range(len(ci))], *([QCHECK] if QCHECK else [])),
                     S("Design tools read them.", *[f"r_{slug(t)}" for t in tools], *[f"f_{slug(f)}" for f in files if f in (light, "$themes.json")]),
                     S("The whole export.")]}]
meta = {"name": "DDD token export", "parent": "main", "noTimeline": True,
        "sectionLabels": {"file": "token files", "group": "token groups", "type": "DTCG types", "tool": "written from and checked by", "reader": "read by"},
        "about": f"The DDD design system as W3C Design Tokens Community Group JSON, generated from elements/d-d-d/tokens: {n_light} tokens in {len(groups)} groups, {n_dark} dark-mode overrides, {len(types)} types. {state}",
        "kindLabels": {"rel": "files, groups and types", "schema": "is read by"},
        "links": {"tokens": GH + f"/webcomponents/tree/master/{TOK}", "export": WCB + build}}
json.dump({"meta": meta, "nodes": nodes, "evidence": {}, "tours": tours}, open("hax-tokens.json", "w"), indent=1, ensure_ascii=False)
print(len(files), "files;", len(groups), "groups;", len(types), "types;", len(sources), "sources;", len(ci), "CI steps;", len(tools), "tools; check:", check)
