#!/usr/bin/env node
//
// generate-command-reference.js
//
// Runs `hax --help` and `hax site --help` via child_process and emits a
// markdown command-reference table to stdout (or a file via --to-file).
// Intended to keep skill command tables from going stale.
//
// Usage:
//   node scripts/generate-command-reference.js
//   node scripts/generate-command-reference.js --to-file docs/command-reference.md
//
// If `hax` is not on PATH, the script prints an error and exits 1.
//

'use strict'

var fs = require('fs')
var cp = require('child_process')
var path = require('path')

function runHelp(args) {
  var result = cp.spawnSync('hax', args, { encoding: 'utf8', timeout: 30000 })
  if (result.error) {
    console.error('ERROR: could not run `hax ' + args.join(' ') + '` — ' + result.error.message)
    process.exit(1)
  }
  if (result.status !== 0 && !result.stdout) {
    console.error('ERROR: `hax ' + args.join(' ') + '` exited ' + result.status)
    if (result.stderr) console.error(result.stderr)
    process.exit(1)
  }
  return result.stdout || ''
}

function parseCommands(helpText) {
  // Parse lines that look like:  command    description
  var commands = []
  var lines = helpText.split('\n')
  var inCommands = false
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i]
    // Skip empty lines and section headers like "Commands:"
    if (line.trim() === '') {
      inCommands = false
      continue
    }
    if (line.trim().endsWith(':') && line.indexOf(' ') === -1) {
      inCommands = true
      continue
    }
    // Match "  command   description" pattern (indented command followed by spaces and text)
    var match = line.match(/^\s{2,}(\S+)\s{2,}(.+)$/)
    if (match) {
      commands.push({ command: match[1], description: match[2].trim() })
    }
  }
  return commands
}

function emitTable(title, commands) {
  var lines = []
  lines.push('## ' + title)
  lines.push('')
  lines.push('| Command | Description |')
  lines.push('|---------|-------------|')
  for (var i = 0; i < commands.length; i++) {
    var c = commands[i]
    lines.push('| `' + c.command + '` | ' + c.description + ' |')
  }
  lines.push('')
  return lines.join('\n')
}

function main() {
  var args = process.argv.slice(2)
  var toFile = null
  for (var i = 0; i < args.length; i++) {
    if (args[i] === '--to-file' && i + 1 < args.length) {
      toFile = args[++i]
    }
  }

  // Check if hax is available
  var check = cp.spawnSync('hax', ['--version'], { encoding: 'utf8', timeout: 10000 })
  if (check.error || check.status !== 0) {
    console.error('ERROR: `hax` is not on PATH. Install it with: npm install --global @haxtheweb/create')
    process.exit(1)
  }

  var ver = (check.stdout || '').trim().split('\n')[0]
  var rootHelp = runHelp(['--help'])
  var siteHelp = runHelp(['site', '--help'])

  var rootCommands = parseCommands(rootHelp)
  var siteCommands = parseCommands(siteHelp)

  var output = []
  output.push('# HAX CLI Command Reference')
  output.push('')
  output.push('> Auto-generated by `scripts/generate-command-reference.js`.')
  output.push('> Reflects `hax ' + ver + '` — regenerate after CLI updates to keep skill tables current.')
  output.push('')
  output.push(emitTable('Top-level commands (`hax --help`)', rootCommands))
  output.push(emitTable('Site commands (`hax site --help`)', siteCommands))

  var result = output.join('\n')

  if (toFile) {
    fs.mkdirSync(path.dirname(toFile), { recursive: true })
    fs.writeFileSync(toFile, result + '\n', 'utf8')
    console.log('Written to ' + toFile)
  } else {
    process.stdout.write(result + '\n')
  }
}

main()
