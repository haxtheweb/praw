#!/usr/bin/env node
/**
 * Aggregates a HAXcms site's authored page content into one transcript-like
 * text file, using the site's llms.txt manifest (preferred) or site.json
 * (local-only fallback), so it can be fed into the LRS rating workflow
 * (see ../SKILL.md).
 *
 * llms.txt is preferred: it lists every page's .md URL in a single fetch,
 * giving clean markdown directly — no JOS tree-walking or HTML parsing.
 *
 * Two source modes, auto-detected from the first argument:
 *   - Live URL: fetches <url>/llms.txt, then each page's .md over HTTP(S)
 *   - Local site checkout: reads <root>/llms.txt (falls back to site.json
 *     + reading .md sidecars from disk if llms.txt is absent)
 *
 * Usage: node extract-site-content.js <siteRootOrUrl> [outDir]
 * Writes <outDir>/site-transcript.txt (concatenated page content) and
 * <outDir>/page-manifest.json ([{index, id, title, slug, location}]).
 * Prints a short summary to stderr; prints the transcript to stdout if
 * no outDir is given.
 */
const fs = require('fs');
const path = require('path');

function isUrl(input) {
  return /^https:\/\//i.test(input);
}

// ---------------------------------------------------------------------------
// llms.txt parsing
// ---------------------------------------------------------------------------

/**
 * Parse an llms.txt file to extract the site title and the list of page
 * markdown links from the `## Pages` section.
 *
 * llms.txt format (per llmstxt.org, as generated by HAXcms):
 *   # Site Title
 *   > Optional description
 *   ## Core resources
 *   - [site.json](url): desc
 *   ## Pages
 *   - [Page Title](url-to-.md): snippet...
 *   - [Page Title](url-to-.md): snippet...
 *
 * Returns { siteTitle, pages: [{title, url}] } where each url ends in .md.
 */
function parseLlmsTxt(text) {
  const lines = String(text || '').split('\n');

  let siteTitle = 'Untitled site';
  for (const line of lines) {
    const m = line.match(/^#\s+(.+)/);
    if (m) {
      siteTitle = m[1].trim();
      break;
    }
  }

  const pages = [];
  let inPagesSection = false;
  for (const line of lines) {
    if (/^##\s+/.test(line)) {
      inPagesSection = /^##\s+Pages/i.test(line);
      continue;
    }
    if (!inPagesSection) continue;
    const m = line.match(/^-\s+\[([^\]]+)\]\(([^)]+)\)/);
    if (m) {
      const title = m[1].trim();
      const url = m[2].trim();
      if (url.endsWith('.md')) pages.push({ title, url });
    }
  }
  return { siteTitle, pages };
}

/** Extract a HAXcms item id (item-<uuid>) from a URL path if present. */
function extractIdFromUrl(url) {
  const m = url.match(/(item-[a-f0-9-]+)/i);
  return m ? m[1] : '';
}

/** Derive a simple slug from a title for manifest citation purposes. */
function slugify(title) {
  return String(title || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Normalize markdown text: collapse excessive whitespace, trim. */
function normalizeMarkdown(md) {
  return String(md || '')
    .replace(/\r\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

// ---------------------------------------------------------------------------
// URL / path resolution
// ---------------------------------------------------------------------------

/** Resolve a possibly-relative URL against a base URL for remote fetching. */
function resolveRemoteUrl(url, baseUrl) {
  if (/^https?:\/\//i.test(url)) return url;
  return baseUrl.replace(/\/+$/, '') + '/' + url.replace(/^\/+/, '');
}

/** Convert a URL (absolute or relative) to a local filesystem path. */
function urlToLocalPath(url, root) {
  let p = url.replace(/^https?:\/\/[^/]+\//, '').replace(/^\/+/, '');
  return path.join(root, p);
}

// ---------------------------------------------------------------------------
// Remote: llms.txt + fetch each .md
// ---------------------------------------------------------------------------

async function fetchText(url) {
  if (typeof fetch !== 'function') {
    throw new Error('This script requires Node.js 18+ (global fetch not found).');
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

async function readRemoteSiteViaLlmsTxt(baseUrlInput) {
  const baseUrl = baseUrlInput.endsWith('/') ? baseUrlInput : baseUrlInput + '/';

  let llmsText;
  try {
    llmsText = await fetchText(baseUrl + 'llms.txt');
  } catch (err) {
    throw new Error(
      `Could not fetch ${baseUrl}llms.txt (${err.message}). ` +
        `HAXcms sites generate this file automatically — verify the URL is a ` +
        `published HAXcms site with llms.txt at the root.`
    );
  }

  const { siteTitle, pages: pageList } = parseLlmsTxt(llmsText);
  if (pageList.length === 0) {
    throw new Error(
      `${baseUrl}llms.txt was fetched but no .md page links were found in its ` +
        `## Pages section. The site may not have published markdown sidecars.`
    );
  }

  const pages = [];
  let mdFailures = 0;
  for (const { title, url } of pageList) {
    const mdUrl = resolveRemoteUrl(url, baseUrl);
    let text = '';
    let fetchedUrl = mdUrl;

    // Try .md first (clean markdown); fall back to .html if the host
    // doesn't serve .md files (e.g. GitHub Pages static deploys).
    try {
      text = normalizeMarkdown(await fetchText(mdUrl));
    } catch (err) {
      mdFailures++;
      const htmlUrl = mdUrl.replace(/\.md$/i, '.html');
      try {
        text = htmlToText(await fetchText(htmlUrl));
        fetchedUrl = htmlUrl;
      } catch (err2) {
        console.error(`Warning: could not fetch page "${title}" (${mdUrl} → ${htmlUrl}): ${err2.message}`);
        continue;
      }
    }
    if (text) pages.push({ title, url: fetchedUrl, text });
  }

  if (mdFailures > 0 && pages.length > 0) {
    console.error(`Note: ${mdFailures} page(s) served .html instead of .md (host does not publish markdown sidecars).`);
  }

  return { siteTitle, siteAuthor: '', pages };
}

// ---------------------------------------------------------------------------
// Local: llms.txt (preferred) or site.json (fallback)
// ---------------------------------------------------------------------------

async function readLocalSiteViaLlmsTxt(root) {
  const llmsPath = path.join(root, 'llms.txt');
  if (!fs.existsSync(llmsPath)) return null; // signal fallback

  const llmsText = fs.readFileSync(llmsPath, 'utf8');
  const { siteTitle, pages: pageList } = parseLlmsTxt(llmsText);
  if (pageList.length === 0) return null; // no pages — try fallback

  const pages = [];
  for (const { title, url } of pageList) {
    const mdPath = urlToLocalPath(url, root);
    let text = '';

    // Try .md first (clean markdown); fall back to .html on disk.
    if (fs.existsSync(mdPath)) {
      try {
        text = normalizeMarkdown(fs.readFileSync(mdPath, 'utf8'));
      } catch (err) {
        console.error(`Warning: could not read .md for "${title}": ${err.message}`);
      }
    }
    if (!text) {
      const htmlPath = mdPath.replace(/\.md$/i, '.html');
      if (fs.existsSync(htmlPath)) {
        try {
          text = htmlToText(fs.readFileSync(htmlPath, 'utf8'));
        } catch (err) {
          console.error(`Warning: could not read page "${title}" at ${htmlPath}: ${err.message}`);
        }
      }
    }
    if (text) pages.push({ title, url, text });
  }

  if (pages.length === 0) return null; // nothing read — try fallback
  return { siteTitle, siteAuthor: '', pages };
}

// --- site.json fallback (local only) ---

/** Build a depth-first reading order from a flat JOS items array. */
function orderItems(items) {
  const byParent = new Map();
  for (const item of items) {
    const key = item.parent || null;
    if (!byParent.has(key)) byParent.set(key, []);
    byParent.get(key).push(item);
  }
  for (const group of byParent.values()) {
    group.sort((a, b) => (a.order || 0) - (b.order || 0));
  }
  const out = [];
  function walk(parentId) {
    const children = byParent.get(parentId) || [];
    for (const child of children) {
      out.push(child);
      walk(child.id);
    }
  }
  walk(null);
  const seen = new Set(out.map((i) => i.id));
  for (const item of items) {
    if (!seen.has(item.id)) out.push(item);
  }
  return out;
}

function isPublished(item) {
  return !(item.metadata && item.metadata.published === false);
}

function decodeEntities(text) {
  return text
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/g, "'")
    .replace(/&rsquo;/gi, '\u2019')
    .replace(/&lsquo;/gi, '\u2018')
    .replace(/&rdquo;/gi, '\u201d')
    .replace(/&ldquo;/gi, '\u201c')
    .replace(/&mdash;/gi, '\u2014')
    .replace(/&ndash;/gi, '\u2013');
}

function htmlToText(html) {
  let text = String(html || '');
  text = text.replace(/<!--[\s\S]*?-->/g, ' ');
  text = text.replace(/<(script|style|template)[^>]*>[\s\S]*?<\/\1>/gi, ' ');
  text = text.replace(/<\/(p|div|li|tr|h[1-6]|blockquote|section|article|figure|figcaption|pre)>/gi, '\n');
  text = text.replace(/<br\s*\/?>/gi, '\n');
  text = text.replace(/<li[^>]*>/gi, '- ');
  text = text.replace(/<[^>]+>/g, ' ');
  text = decodeEntities(text);
  text = text.replace(/[ \t]+/g, ' ');
  text = text.replace(/\n[ \t]+/g, '\n');
  text = text.replace(/\n{3,}/g, '\n\n');
  return text.trim();
}

async function readLocalSiteViaSiteJson(root) {
  const siteJsonPath = path.join(root, 'site.json');
  if (!fs.existsSync(siteJsonPath)) {
    throw new Error(
      `No llms.txt or site.json found at ${root}. ` +
        `For a live site, pass the URL instead. For a local checkout, ` +
        `ensure llms.txt (preferred) or site.json exists at the root.`
    );
  }
  console.error('Falling back to site.json (no llms.txt found)...');

  const manifest = JSON.parse(fs.readFileSync(siteJsonPath, 'utf8'));
  const items = orderItems((manifest.items || []).filter(isPublished));

  const pages = [];
  for (const item of items) {
    if (!item.location) continue;
    const htmlPath = path.join(root, item.location);
    const mdPath = htmlPath.replace(/\.html?$/i, '.md');
    let text = '';
    // Prefer .md sidecar (clean markdown), fall back to HTML
    if (fs.existsSync(mdPath)) {
      try {
        text = normalizeMarkdown(fs.readFileSync(mdPath, 'utf8'));
      } catch (err) {
        console.error(`Warning: could not read .md for "${item.title}": ${err.message}`);
      }
    }
    if (!text) {
      try {
        text = htmlToText(fs.readFileSync(htmlPath, 'utf8'));
      } catch (err) {
        console.error(`Warning: could not read page "${item.title}" at ${htmlPath}: ${err.message}`);
        continue;
      }
    }
    if (text) {
      pages.push({
        title: item.title || item.slug || item.id,
        url: item.location,
        text,
      });
    }
  }

  const siteTitle = (manifest.title || '').trim() || 'Untitled site';
  const siteAuthor =
    (manifest.author || (manifest.metadata && manifest.metadata.author && manifest.metadata.author.name) || '').trim();

  return { siteTitle, siteAuthor, pages };
}

// ---------------------------------------------------------------------------
// Output assembly
// ---------------------------------------------------------------------------

function buildOutput(siteTitle, siteAuthor, pages) {
  const manifestEntries = pages.map(({ title, url }, index) => ({
    index,
    id: extractIdFromUrl(url),
    title: title || `page ${index + 1}`,
    slug: slugify(title),
    location: url,
  }));

  const blocks = pages.map(({ title, text }, index) => {
    const label = title || `page ${index + 1}`;
    return `=== PAGE ${index + 1}: ${label} ===\n${text}`;
  });

  const header = `SITE: ${siteTitle}${siteAuthor ? `\nAUTHOR: ${siteAuthor}` : ''}\nPAGE COUNT: ${pages.length}\n`;

  return {
    transcript: header + '\n' + blocks.join('\n\n'),
    manifestEntries,
    siteTitle,
    siteAuthor,
  };
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  const [, , source, outDir] = process.argv;
  if (!source) {
    console.error('Usage: node extract-site-content.js <siteRootOrUrl> [outDir]');
    process.exit(1);
  }

  let result;
  if (isUrl(source)) {
    result = await readRemoteSiteViaLlmsTxt(source);
  } else {
    const root = path.resolve(source);
    result = await readLocalSiteViaLlmsTxt(root);
    if (!result) result = await readLocalSiteViaSiteJson(root);
  }

  if (result.pages.length === 0) {
    console.error('Error: no readable pages with content were found.');
    process.exit(1);
  }

  const { transcript, manifestEntries, siteTitle, siteAuthor } = buildOutput(
    result.siteTitle,
    result.siteAuthor,
    result.pages
  );

  if (outDir) {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'site-transcript.txt'), transcript, 'utf8');
    fs.writeFileSync(path.join(outDir, 'page-manifest.json'), JSON.stringify(manifestEntries, null, 2), 'utf8');
    console.error(
      `Wrote ${result.pages.length} page(s) (site: "${siteTitle}"${siteAuthor ? `, author: "${siteAuthor}"` : ''}) to ${path.join(outDir, 'site-transcript.txt')}`
    );
  } else {
    console.log(transcript);
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
